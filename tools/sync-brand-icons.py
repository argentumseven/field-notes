#!/usr/bin/env python3
"""Reuse the APK's launcher artwork in the web and shared Compose headers."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ANDROID = "{http://schemas.android.com/apk/res/android}"
RES = ROOT / "apps/mobile/src/androidMain/res"


def outputs():
    colors = ET.parse(RES / "values/colors.xml").getroot()
    background = next(c.text for c in colors if c.attrib.get("name") == "icon_background")
    vector = ET.parse(RES / "drawable/ic_note_foreground.xml").getroot()
    paths = [(p.attrib[ANDROID + "fillColor"], p.attrib[ANDROID + "pathData"]) for p in vector]
    svg = '<!-- Generated by tools/sync-brand-icons.py from the APK launcher artwork. -->\n'
    svg += '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">\n'
    svg += f'  <rect x="18" y="18" width="72" height="72" rx="16" fill="{background}"/>\n'
    for color, path in paths:
        svg += f'  <path fill="{color}" d="{path}"/>\n'
    svg += '</svg>\n'
    # Adaptive launchers mask a 72-unit area of the 108-unit source. Use that
    # same safe area, without changing the user's installed launcher artwork.
    tile = "M34,18 H74 Q90,18 90,34 V74 Q90,90 74,90 H34 Q18,90 18,74 V34 Q18,18 34,18 Z"
    kotlin = '''// Generated by tools/sync-brand-icons.py from the APK launcher artwork.
package org.fieldnotes.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

internal val LauncherMark: ImageVector by lazy {
    ImageVector.Builder("Field Notes", 32.dp, 32.dp, 72f, 72f).apply {
        addGroup(translationX = -18f, translationY = -18f)
'''
    for color, path in [(background, tile), *paths]:
        kotlin += f'        addPath(PathParser().parsePathString("{path}").toNodes(), fill = SolidColor(Color(0xFF{color[1:]})))\n'
    kotlin += '''        clearGroup()
    }.build()
}
'''
    return {
        ROOT / "apps/admin/field-notes-icon.svg": svg,
        ROOT / "apps/mobile/src/commonMain/kotlin/org/fieldnotes/ui/LauncherMark.kt": kotlin,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Launcher artwork changed; run python3 tools/sync-brand-icons.py: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
