#!/usr/bin/env python3
"""Keep web/native item-category vocabularies in sync with the server's source."""
import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def outputs():
    profiles = json.loads((ROOT / 'shared/item-contexts.json').read_text())
    assert set(profiles) == {'general', 'groceries', 'shopping', 'home', 'food', 'errands', 'work', 'personal'}
    for profile in profiles.values():
        assert set(profile) == {'label', 'choices'}
        assert isinstance(profile['label'], str) and profile['label']
        assert len(profile['choices']) == len(set(profile['choices']))
        assert all(isinstance(v, str) and 0 < len(v) <= 80 and not any(ord(c) < 32 for c in v) for v in profile['choices'])
    assert profiles['general']['choices'] == []
    header = '// Generated by tools/sync-item-contexts.py from shared/item-contexts.json.\n'
    web = header + 'const itemContextProfiles = ' + json.dumps(profiles, indent=2, ensure_ascii=False) + ';\n'
    native = header + 'package org.fieldnotes.domain\n\ninternal val itemContextProfiles = linkedMapOf(\n'
    for key, profile in profiles.items():
        quoted = lambda value: json.dumps(value, ensure_ascii=False).replace('$', '\\$')
        values = ', '.join(quoted(v) for v in profile['choices'])
        native += f'    {quoted(key)} to ItemContext({quoted(key)}, {quoted(profile["label"])}, listOf({values})),\n'
    native += ')\n'
    return {
        ROOT / 'apps/admin/item-context-data.js': web,
        ROOT / 'apps/mobile/src/commonMain/kotlin/org/fieldnotes/domain/ItemContextData.kt': native,
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f'Item context data is stale: {path.relative_to(ROOT)}. Run python3 tools/sync-item-contexts.py')
        else:
            path.write_text(expected)
